export type Dictionary = typeof sr;

const dictionaries: Record<Locale, Dictionary> = { sr, en };

export function getDictionary(locale: Locale): Dictionary {
  return dictionaries[locale];
}

export function categoryLabelFor(
  category: Category | "sve",
  dict: Dictionary,
) {
  return dict.filters.categories[category];
}

export function colorLabelFor(color: ColorId, dict: Dictionary) {
  return dict.filters.colors[color];
}

export function priceLabelFor(price: PriceId, dict: Dictionary) {
  return dict.filters.prices[price];
}
